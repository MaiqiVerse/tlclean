@contextmanager
def patched_random_labels(task_obj, task_name: str, seed: int):
    """Temporarily replace _build_fewshot_prefix with random-label demos.

    Restores the original on exit. Identical logic to
    test_unified_task_recognition._monkey_patch_random_labels except
    cleanly reverted.
    """
    label_field, label_names, format_fn = _get_label_field_and_names(task_name)
    n_classes = len(label_names)
    original = task_obj._build_fewshot_prefix

    def new_prefix():
        examples = task_obj._get_fewshot_examples()
        if not examples:
            return ""
        rng = random.Random(seed + 12345)
        demos = [
            format_fn(ex, label_names[rng.randint(0, n_classes - 1)])
            for ex in examples
        ]
        return "\n\n".join(demos) + "\n\n"

    task_obj._build_fewshot_prefix = new_prefix
    try:
        yield
    finally:
        task_obj._build_fewshot_prefix = original


@contextmanager
def patched_random_abstract_labels(
    task_obj, task_name: str, abstract_labels: list[str], seed: int,
):
    """Like patched_abstract_labels, but each demo gets a UNIFORMLY RANDOM
    abstract label (sampled per-demo, not from the demo's true class).

    This is the Pan-Random analog for the abstract/UUID label space:
        C_full uuid       = UUID labels with consistent class -> UUID mapping (true mapping)
        C_rand uuid       = UUID labels with per-demo random mapping (this function)
        gold - rand_uuid  = TR (format) + 0       (no prior, no TL)
        uuid - rand_uuid  = TL only               (no prior contamination)

    Use as the C_rand contrast for prior-clean TL-score discovery.
    """
    label_field, original_labels, make_fmt, query_fn = _get_task_info(task_name)
    n_abs = len(abstract_labels)

    saved = {
        "_build_fewshot_prefix": task_obj._build_fewshot_prefix,
        "doc_to_text": task_obj.doc_to_text,
    }
    format_fn = make_fmt(abstract_labels)

    def new_prefix():
        examples = task_obj._get_fewshot_examples()
        if not examples:
            return ""
        rng = random.Random(seed)
        demos = [
            format_fn(ex, abstract_labels[rng.randint(0, n_abs - 1)])
            for ex in examples
        ]
        return "\n\n".join(demos) + "\n\n"

    def new_doc_to_text(doc, *a, **kw):
        # Synthetic tasks carry their fewshot demos INSIDE each test doc
        # (per-prompt random hidden function), and read them in
        # _get_fewshot_examples via self._current_doc. Replacing doc_to_text
        # here bypasses the task's own stash, so we set it for any task that
        # exposes the attribute. No-op for TREC/banking/etc. that pull demos
        # from a global pool.
        if hasattr(task_obj, "_current_doc"):
            task_obj._current_doc = doc
        return new_prefix() + query_fn(doc)

    task_obj._build_fewshot_prefix = new_prefix
    task_obj.doc_to_text = new_doc_to_text
    try:
        yield
    finally:
        for attr, val in saved.items():
            setattr(task_obj, attr, val)


@contextmanager
def patched_abstract_labels(task_obj, task_name: str, abstract_labels: list[str]):
    """Temporarily replace doc_to_text / doc_to_target / doc_to_choice /
    _build_fewshot_prefix with abstract-label versions. Restores on exit.

    Identical logic to test_unified_task_learning._monkey_patch_abstract_labels
    except cleanly reverted.
    """
    label_field, original_labels, make_fmt, query_fn = _get_task_info(task_name)
    n_classes = len(original_labels)
    assert len(abstract_labels) == n_classes

    saved = {
        "_build_fewshot_prefix": task_obj._build_fewshot_prefix,
        "doc_to_text": task_obj.doc_to_text,
        "doc_to_target": task_obj.doc_to_target,
        "doc_to_choice": task_obj.doc_to_choice,
    }
    format_fn = make_fmt(abstract_labels)

    def new_prefix():
        examples = task_obj._get_fewshot_examples()
        if not examples:
            return ""
        demos = [
            format_fn(ex, abstract_labels[ex[label_field]])
            for ex in examples
        ]
        return "\n\n".join(demos) + "\n\n"

    def new_doc_to_text(doc, *a, **kw):
        # See note in patched_random_abstract_labels: synthetic tasks need
        # _current_doc stashed because their demos live inside each test doc.
        if hasattr(task_obj, "_current_doc"):
            task_obj._current_doc = doc
        return new_prefix() + query_fn(doc)

    def new_doc_to_target(doc, *a, **kw):
        return f" {abstract_labels[doc[label_field]]}"

    abstract_choices = [f" {al}" for al in abstract_labels]

    def new_doc_to_choice(doc, *a, **kw):
        return abstract_choices

    task_obj._build_fewshot_prefix = new_prefix
    task_obj.doc_to_text = new_doc_to_text
    task_obj.doc_to_target = new_doc_to_target
    task_obj.doc_to_choice = new_doc_to_choice
    try:
        yield
    finally:
        for attr, val in saved.items():
            setattr(task_obj, attr, val)


