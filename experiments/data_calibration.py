# Token-id discovery via tokenize-and-diff
# ---------------------------------------------------------------------------

def first_label_token_id_in_context(
    tokenizer, prompt: str, label_with_leading_space: str
) -> int:
    """Token id of the first token of `label_with_leading_space` (e.g.
    " positive") when it appears IMMEDIATELY after `prompt`.

    Uses tokenize-and-diff: tokenization of `prompt` alone vs
    `prompt + label` may differ at the boundary (BPE / SP merges). We
    walk both lists from index 0 and return the first index where they
    diverge OR the first token of the appended portion if they share a
    prefix.
    """
    p_ids = tokenizer(prompt, add_special_tokens=True).input_ids
    full_ids = tokenizer(prompt + label_with_leading_space, add_special_tokens=True).input_ids

    # Walk in lock-step; first index of divergence is the label-start token.
    for i in range(len(p_ids)):
        if i >= len(full_ids):
            break
        if p_ids[i] != full_ids[i]:
            return int(full_ids[i])
    # If we get here, full_ids strictly extends p_ids; label starts at len(p_ids).
    if len(full_ids) > len(p_ids):
        return int(full_ids[len(p_ids)])
    raise RuntimeError(
        f"Tokenize-and-diff failed: prompt and prompt+label tokenize identically. "
        f"label was {label_with_leading_space!r}"
    )


def compute_label_token_ids(
    tokenizer, sample_prompt: str, label_names: list[str]
) -> list[int]:
    """For each label, find its first-token id when appended to sample_prompt.

    All labels are prefixed with ' ' (matching the lm-eval `doc_to_target`
    convention of `f' {label}'`).
    """
    return [
        first_label_token_id_in_context(tokenizer, sample_prompt, f" {lab}")
        for lab in label_names
    ]


def _verify_label_token_ids_match_inference_context(
    tokenizer, rendered_prompt: str, abstract_labels: list[str],
    label_token_ids: list[int],
) -> None:
    """Fail-fast: the stored label_token_ids MUST equal the first token that
    each label produces when appended to the *actual inference context* — the
    query block the model conditions on (everything after the last demo).

    A real prompt is "<demo>\\n\\n<demo>\\n\\n...\\n\\n<query ending in e.g.
    'Type:'>". At inference the model has emitted the query tail and predicts
    the next token; that token is what argmax-over-labels is scored against.
    If label_token_ids were computed against a context that tokenizes the
    appended label differently (e.g. a stale file holding pool subword
    fragments like 'ation'/'ode' instead of ' A'/' C'), every accuracy number
    silently collapses to ~chance. Raise loudly instead of writing a bad file.
    """
    query_tail = rendered_prompt.split("\n\n")[-1]
    recomputed = [
        first_label_token_id_in_context(tokenizer, query_tail, f" {lab}")
        for lab in abstract_labels
    ]
    mismatches = [
        (k, abstract_labels[k], label_token_ids[k], recomputed[k])
        for k in range(len(abstract_labels))
        if label_token_ids[k] != recomputed[k]
    ]
    if mismatches:
        sample = mismatches[:10]
        detail = "\n".join(
            f"    k={k:>3} label={lab!r:>6} stored={st:>6} "
            f"({tokenizer.decode([st])!r}) != inference_ctx={rc:>6} "
            f"({tokenizer.decode([rc])!r})"
            for (k, lab, st, rc) in sample
        )
        raise RuntimeError(
            f"label_token_ids do not match the inference-context tokenization "
            f"on {len(mismatches)}/{len(abstract_labels)} labels. The stored ids "
            f"would make every argmax-over-labels accuracy measurement score the "
            f"model against the WRONG token.\n"
            f"  query tail: ...{query_tail[-50:]!r}\n"
            f"  first mismatches (k, label, stored_id, inference_ctx_id):\n{detail}"
        )
    print(f"[setup] label_token_ids verified against inference context: "
          f"{len(abstract_labels)}/{len(abstract_labels)} match")


# ---------------------------------------------------------------------------
# Reverse loader: pair gold + random for TL-score
# ---------------------------------------------------------------------------

def load_paired_for_tl_score(
    gold_path: str | Path,
    random_path: str | Path,
) -> tuple[list[str], list[list[str]], list[int]]:
    """Load gold + random JSONL produced by this script and pair them by
    doc_idx for tools.tl_score.compute_tl_scores.

    Returns:
        prompts_gold:        list[N str]
        prompts_random:      list[N list[M str]]  (sorted by random_seed_s)
        true_label_token_ids: list[N int]
    """
    gold_by_idx: dict[int, dict] = {}
    with open(gold_path, encoding="utf-8") as f:
        next(f)  # header
        for line in f:
            obj = json.loads(line)
            gold_by_idx[obj["doc_idx"]] = obj

    rand_by_idx: dict[int, list[dict]] = defaultdict(list)
    with open(random_path, encoding="utf-8") as f:
        next(f)  # header
        for line in f:
            obj = json.loads(line)
            rand_by_idx[obj["doc_idx"]].append(obj)

    doc_indices = sorted(gold_by_idx.keys())
    prompts_gold: list[str] = []
    prompts_random: list[list[str]] = []
    true_label_token_ids: list[int] = []
    for di in doc_indices:
        prompts_gold.append(gold_by_idx[di]["prompt"])
        prompts_random.append([
            r["prompt"]
            for r in sorted(rand_by_idx[di], key=lambda x: x.get("random_seed_s", 0))
        ])
        true_label_token_ids.append(gold_by_idx[di]["true_label_token_id"])
    return prompts_gold, prompts_random, true_label_token_ids


