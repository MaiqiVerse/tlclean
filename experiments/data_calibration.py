"""Real-task calibration prompt generator.

Produces JSONL prompt files from lm-eval tasks (TREC, Yelp, SST-2, ...) using
the existing test_unified_*.py infrastructure. The outputs are consumable by:
    - tools.tl_score.compute_tl_scores                  (needs gold + random×M)
    - experiments.exp_identity_verification             (needs UUID prompts)

Three output files per (task, K, seed):
    calibration_<task>_K<K>_seed<S>_gold.jsonl     (N records)
    calibration_<task>_K<K>_seed<S>_random.jsonl   (N * M_random records)
    calibration_<task>_K<K>_seed<S>_uuid.jsonl     (N records)

Each file starts with a HEADER line:
    {"header": true, "task": ..., "K": ..., "seed": ...,
     "label_scheme": "gold" | "random_pan" | "uuid",
     "label_token_ids": [n_classes single-token ids],
     "abstract_labels": [n_classes strings]   # uuid only
    }

Followed by per-prompt records:
    {"prompt": "...", "true_label_token_id": int,
     "doc_idx": int, "true_class_idx": int, "task": ..., "K": ...,
     "label_scheme": ..., "random_seed_s": int  # random only}

`true_label_token_id` is the first token of the class label as it appears
right after the prompt's last token (boundary tokenization handled via
tokenize-and-diff).

For TL-score discovery, prompts are paired across gold and random files by
`doc_idx`. Use `load_paired_for_tl_score` to do this.
"""

