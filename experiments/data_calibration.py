def _load_single_token_pool(tokenizer) -> list[str]:
    """Load pre-scanned short alphabetic single-token strings for this
    tokenizer, generated by ``tools/scan_single_token_pool.py``.

    Looks for ``<repo>/tools/single_token_pool_<safe_name>.json`` where
    ``safe_name`` is ``tokenizer.name_or_path`` with ``/`` and ``:``
    replaced by ``_``. Returns empty list if no pool file exists (caller
    falls back to the built-in A-Z / a-z candidates only).
    """
    name = getattr(tokenizer, "name_or_path", None)
    if not name:
        return []
    safe_name = name.replace("/", "_").replace(":", "_")
    pool_path = (
        Path(__file__).resolve().parent.parent
        / "tools" / f"single_token_pool_{safe_name}.json"
    )
    if not pool_path.is_file():
        return []
    with open(pool_path, encoding="utf-8") as f:
        payload = json.load(f)
    return list(payload.get("candidates", []))


def discover_single_token_labels(
    tokenizer,
    sample_prompt_ending: str,
    n_classes: int,
    exclude_surfaces: Optional[set[str]] = None,
) -> list[str]:
    """Pick n_classes label strings whose first appended token to
    `sample_prompt_ending` is unique across classes AND not a "phantom
    space" (Llama-2 leading-space marker 29871).

    Strategy: enumerate single-character candidates (A-Z, a-z), then any
    pre-scanned short alphabetic single tokens loaded from the tokenizer
    pool JSON (see ``tools/scan_single_token_pool.py``). For each, tokenize
    `sample_prompt_ending + ' ' + cand` and check the first new token id
    against already-accepted ones. Accept iff distinct AND not just
    phantom space.

    For tasks with more than ~52 classes (Banking77, CLINC150), run the
    pool scanner once to enable lookup beyond a-z / A-Z without falling
    back to digit-prefixed candidates (phantom-space hazard) or
    semantically-loaded punctuation.

    The phantom-space token id is auto-detected by tokenizing ' x' and
    checking if the first token decodes to empty/whitespace.

    ``exclude_surfaces`` lets the caller blacklist surface strings already
    used by the task's gold labels — needed when gold labels are themselves
    single-token (e.g. synthetic_linear's ``A``–``F``), so that the abstract
    label set does not collide with gold and accidentally render uuid prompts
    identical to gold prompts.
    """
    # Detect phantom-space token id (if any) for this tokenizer
    probe = tokenizer(" Xq9k", add_special_tokens=False).input_ids
    phantom_id: Optional[int] = None
    if len(probe) > 1:
        first_decoded = tokenizer.decode([probe[0]])
        if first_decoded == "" or first_decoded.isspace():
            phantom_id = probe[0]

    exclude = exclude_surfaces or set()

    p_ids = tokenizer(sample_prompt_ending, add_special_tokens=True).input_ids
    surfaces: list[str] = []
    seen_token_ids: set[int] = set()

    candidates: list[str] = []
    candidates += list("ABCDEFGHIJKLMNOPQRSTUVWXYZ")     # 26 capitals
    candidates += list("abcdefghijklmnopqrstuvwxyz")     # 26 lowercase
    # Pool-scanned short alphabetic tokens (de-duplicated against above).
    # Empty if no pool JSON exists for this tokenizer.
    pool_extra = [c for c in _load_single_token_pool(tokenizer)
                  if c not in set(candidates)]
    candidates += pool_extra

    for cand in candidates:
        # Skip surfaces blacklisted by the caller (typically: gold label set).
        if cand in exclude:
            continue
        full_ids = tokenizer(sample_prompt_ending + " " + cand,
                             add_special_tokens=True).input_ids
        # Find first divergence
        first_tok = None
        for i in range(len(p_ids)):
            if i >= len(full_ids):
                break
            if p_ids[i] != full_ids[i]:
                first_tok = int(full_ids[i])
                break
        if first_tok is None and len(full_ids) > len(p_ids):
            first_tok = int(full_ids[len(p_ids)])
        if first_tok is None:
            continue
        # Reject if first token is the phantom space (uninformative)
        if phantom_id is not None and first_tok == phantom_id:
            continue
        # Reject if first token already taken by another class
        if first_tok in seen_token_ids:
            continue
        seen_token_ids.add(first_tok)
        surfaces.append(cand)
        if len(surfaces) >= n_classes:
            break

    if len(surfaces) < n_classes:
        raise RuntimeError(
            f"Could only find {len(surfaces)}/{n_classes} single-token-distinct "
            f"labels in context. Sample prompt ends with: "
            f"...{sample_prompt_ending[-80:]!r}"
        )
    return surfaces


