def _task_source(cls):
    """The text of a task class, for the categorical checks below.

    inspect.getsource works when the class's module is in sys.modules; lm_eval
    loads task modules from file specs without registering them, and then
    inspect reports a 'built-in class'. The file under tasks/ named after the
    module is the same source, so it is read directly in that case.
    """
    import inspect as _inspect
    try:
        return _inspect.getsource(cls)
    except (TypeError, OSError):
        pass
    from test_unified import TASK_DIR
    p = Path(TASK_DIR) / f"{cls.__module__}.py"
    if p.is_file():
        return p.read_text(encoding="utf-8")
    raise SystemExit(
        f"cannot locate the source of {cls.__name__} (module "
        f"{cls.__module__!r}) to check that its draw reads _allowed_classes")


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--task", required=True,
                        help="lm-eval task name (e.g. trec_fine_per_class, yelp_full_per_class)")
    parser.add_argument("--K", type=int, required=True, help="num fewshot demos")
    parser.add_argument("--n-queries", type=int, default=100,
                        help="number of query docs to render")
    parser.add_argument("--M-random", type=int, default=5,
                        help="random-label resamplings per query")
    parser.add_argument("--seed", type=int, default=42)
    parser.add_argument("--label-type", default="single_token",
                        choices=["uuid", "number", "letter", "single_token"],
                        help="'single_token' (default) picks labels that tokenize "
                             "to distinct single tokens in the prompt's tail "
                             "context; recommended for projection-based analysis. "
                             "Others use the generate_abstract_labels generators.")
    parser.add_argument("--model", default="meta-llama/Llama-2-7b-hf",
                        help="HF model id (only tokenizer is loaded)")
    parser.add_argument("--output", default="data/")
    parser.add_argument("--restrict-to-train-classes",
                        action=argparse.BooleanOptionalAction, default=True,
                        help="Filter test docs to those whose true class has "
                             "at least one train example -- without a demo "
                             "there is nothing to learn the mapping from. On "
                             "TREC-fine all 50 fine classes occur in train, so "
                             "this now drops nothing; it used to appear to drop "
                             "20 classes because of a label-parsing bug fixed "
                             "on 2026-08-31. Default True.")
    parser.add_argument("--reuse-labels", default=None,
                        help="Path to an existing *_uuid.jsonl whose "
                             "abstract_labels are adopted verbatim instead "
                             "of being re-discovered. The discovery reads a "
                             "SAMPLE PROMPT, which differs per demo seed, so "
                             "each seed would otherwise get its own label "
                             "mapping and the candidate token set would "
                             "drift between seeds. Point seeds 43/44 at the "
                             "seed-42 file.")
    parser.add_argument("--exclude-validation", default=None,
                        help="Path to the query manifest whose "
                             "`validation_by_seed[str(--seed)]` entries must "
                             "NOT appear as demonstrations -- THIS seed's "
                             "own draw, not a set shared by all three. "
                             "Validation is reserved from the train split "
                             "first and demos are drawn from what is left; "
                             "without this the two overlap and a validation "
                             "query can have its own answer in the prompt.")
    parser.add_argument("--allow-different-K", action="store_true",
                        help="permit --reuse-labels to adopt surfaces from a "
                             "file rendered at a DIFFERENT K. Off by default. "
                             "The abstract surfaces do not depend on how many "
                             "demonstrations are shown, and the property the "
                             "guard protects -- that each surface is still one "
                             "token in THIS prompt -- is verified separately "
                             "and strictly below, by recomputing the ids in "
                             "this run's rendered prompt and comparing them "
                             "against what the model actually sees after "
                             "'Type:'. What makes crossing K NECESSARY rather "
                             "than convenient: the readout is candidate-"
                             "conditional over a fixed token set, so two runs "
                             "at different K that discovered their own "
                             "surfaces would normalise over DIFFERENT sets and "
                             "their NLL difference would not be an effect of "
                             "K at all. Recorded in the header when used.")
    parser.add_argument("--restrict-to-test-classes",
                        action=argparse.BooleanOptionalAction, default=True,
                        help="Filter DEMONSTRATIONS to classes that occur in "
                             "the test split. The mirror image of "
                             "--restrict-to-train-classes: that one drops "
                             "queries no demo can answer, this one drops demos "
                             "no query can ask about. On TREC-fine 8 of the 50 "
                             "classes never appear in the 500-question test "
                             "set, so their demos only lengthen the prompt and "
                             "add candidate logits that can never be correct. "
                             "Together the two flags give the ELIGIBLE class "
                             "space, train n test. Default True.")
    args = parser.parse_args()

    output_dir = Path(args.output)
    output_dir.mkdir(parents=True, exist_ok=True)

    # Tokenizer only (no model weights)
    from transformers import AutoTokenizer
    print(f"[setup] loading tokenizer {args.model}...")
    tok = AutoTokenizer.from_pretrained(args.model)
    sys.path.insert(0, str(Path(__file__).resolve().parent.parent))
    from tools.label_space import tokenizer_provenance as _tok_prov
    _prov = _tok_prov(tok, args.model)
    print(f"[setup] tokenizer {_prov['tokenizer_class']}, vocab "
          f"{_prov['vocab_size']}, sha256 {_prov['vocab_sha256'][:16]}...")

    # Load lm-eval task
    print(f"[setup] loading task {args.task} (K={args.K}, seed={args.seed})...")
    tm = lm_eval.tasks.TaskManager(include_path=TASK_DIR)
    task_dict = lm_eval.tasks.get_task_dict([args.task], task_manager=tm)
    task_obj = task_dict[args.task]
    # Propagate --n-queries to the task's generator config BEFORE set_fewshot
    # triggers download(). Tasks like synthetic_linear / monk_per_class hash the
    # per-prompt cache by n_queries; the class-default (250) can exceed task
    # caps (e.g. Monk-2 balanced cap = 156). Doing this before download() also
    # avoids generating prompts we'll never look at.
    if hasattr(task_obj, "_n_queries"):
        task_obj._n_queries = args.n_queries
    task_obj.download()
    task_obj.set_fewshot(num_fewshot=args.K, seed=args.seed)

    # Task label info (needed for the train-class filter below)
    label_field, label_names, _ = _get_label_field_and_names(args.task)
    label_field2, original_labels, _, _ = _get_task_info(args.task)
    assert label_field == label_field2 and label_names == original_labels
    n_classes = len(label_names)
    print(f"[setup] task has {n_classes} classes ('{label_names[0]}'...'{label_names[-1]}')")

    # Test docs (queries). lm-eval's test_docs() preserves the dataset's
    # native order, which for many tasks (e.g. TREC) is grouped by class.
    # Taking the first N would give a class-biased subset (we measured
    # majority_class_rate = 0.22 reproducibly on the first 100 TREC-fine
    # docs vs ~0.04 expected under uniform 50-way). Shuffle with the
    # provided seed to get a class-representative sample while staying
    # reproducible.
    test_docs = list(task_obj.test_docs())
    total_docs_pre_filter = len(test_docs)

    # Find which classes actually have train examples; the rest are
    # structurally unanswerable for TL (no demo will ever appear for them).
    train_classes = sorted({
        int(doc[label_field]) for doc in task_obj.dataset["train"]
    })
    n_train_classes = len(train_classes)
    train_classes_set = set(train_classes)
    print(f"[setup] train-classes: {n_train_classes} of {n_classes} fine classes "
          f"have >=1 train example")
    if n_train_classes < n_classes:
        missing = sorted(set(range(n_classes)) - train_classes_set)
        missing_names = [label_names[i] for i in missing[:5]]
        print(f"[setup]   {n_classes - n_train_classes} classes have NO train "
              f"example (e.g. {missing_names!r}{'...' if len(missing) > 5 else ''})")

    # The mirror restriction: demos only for classes a query can be about.
    # Must precede any rendering, and set_fewshot is re-called so the cached
    # draw is rebuilt under the restriction rather than reused.
    _man_eligible, _man_sha = None, None
    if args.exclude_validation:
        import json as _json
        _man = _json.loads(Path(args.exclude_validation).read_text(
            encoding="utf-8"))
        _man_eligible = _man.get("eligible_classes")
        import hashlib as _hl
        _man_sha = _hl.sha256(
            Path(args.exclude_validation).read_bytes()).hexdigest()
        if _man.get("candidate_space"):
            raise SystemExit(
                f"{args.exclude_validation} still carries 'candidate_space'. "
                "That field held tokenizer-specific ids in a model-independent "
                "file and was removed on 2026-09-01; rebuild the manifest "
                "before generating calibration against it.")
        # THIS SEED's reservation. Validation is drawn per prefix seed
        # (14.0a), and a single list withheld seed 42's queries from every
        # seed's demonstrations. The VOLUME was right -- 144 rows either way
        # -- and the IDENTITY was wrong for two of the three, so their
        # prompts would have matched no other consumer's prefix. (An earlier
        # note here said "three times as much", which is not what the old
        # code did.)
        _vbs = _man.get("validation_by_seed")
        if _vbs is None:
            raise SystemExit(
                f"{args.exclude_validation}: no 'validation_by_seed'. A "
                "manifest "
                "with a single 'validation' list predates section 14.0a and "
                "describes a draw that no longer exists; rebuild it with "
                "tools/build_query_manifest.py.")
        if str(args.seed) not in _vbs:
            raise SystemExit(
                f"{args.exclude_validation}: no validation for seed "
                f"{args.seed}; "
                f"it carries {sorted(_vbs)}")
        _res = {(int(v["class_idx"]), v["source_text"])
                for v in _vbs[str(args.seed)]}
        task_obj._excluded_docs = _res
        task_obj.set_fewshot(num_fewshot=args.K, seed=args.seed)
        print(f"[setup] --exclude-validation: {len(_res)} train docs "
              f"reserved for SEED {args.seed}'s validation are "
              "withheld from its demonstrations")

    # ONE definition of the class space, not one per tool. Computing it here
    # independently is how the two drifted: this file had train n test = 42
    # while the manifest applied the minimum-count condition and had 36, so the
    # prefix in the calibration files would not have been the prefix the
    # manifest described -- and nothing would have raised until a prefix
    # verification much later, if at all.
    sys.path.insert(0, str(Path(__file__).resolve().parent.parent))
    from tools.prereg_task import eligible_classes as _eligible_classes
    test_classes = sorted({int(d[label_field]) for d in test_docs})
    eligible = _eligible_classes(task_obj, args.task)
    if _man_eligible is not None and list(_man_eligible) != list(eligible):
        raise SystemExit(
            f"class-space mismatch: the manifest records {len(_man_eligible)} "
            f"eligible classes, this run computes {len(eligible)}. They must "
            "agree exactly -- the manifest is the single source of truth for "
            f"the class space. manifest={list(_man_eligible)} "
            f"here={list(eligible)}")
    if args.restrict_to_test_classes:
        train_only = sorted(set(train_classes) - set(test_classes))
        task_obj._allowed_classes = set(eligible)
        # A RESTRICTION THE TASK DOES NOT READ IS NOT A RESTRICTION. Only
        # TRECFinePerClass's draw consults _allowed_classes; every other
        # per-class task draws every train class and the header would still
        # say "limited to the eligible classes". Refuse when it would matter.
        if set(eligible) != set(train_classes) and \
                "_allowed_classes" not in _task_source(type(task_obj)):
            raise SystemExit(
                f"--restrict-to-test-classes: {type(task_obj).__name__}'s "
                "demonstration draw does not read _allowed_classes, so the "
                f"{len(set(train_classes) - set(eligible))} ineligible "
                "classes would still be drawn while the header claimed "
                "otherwise. Add the restriction to the task the way "
                "TRECFinePerClass has it, or pass "
                "--no-restrict-to-test-classes.")
        task_obj.set_fewshot(num_fewshot=args.K, seed=args.seed)
        print(f"[setup] --restrict-to-test-classes ON: demos limited to the "
              f"{len(eligible)} ELIGIBLE classes (train n test); dropped "
              f"{len(train_only)} train-only classes {train_only}")
    else:
        print(f"[setup] --no-restrict-to-test-classes: demos span all "
              f"{len(train_classes)} train classes, including "
              f"{len(set(train_classes) - set(test_classes))} that no test "
              "query can ever be about")

    if _man_eligible is not None:
        before = len(test_docs)
        _elig = {int(c) for c in _man_eligible}
        test_docs = [d for d in test_docs if int(d[label_field]) in _elig]
        print(f"[setup] manifest eligible classes: dropped "
              f"{before - len(test_docs)} test docs outside the "
              f"{len(_elig)}-class decision space "
              f"({len(test_docs)} kept) -- generating queries for filtered-out "
              "classes would put experiments-outside-the-experiment in the file")

    if args.restrict_to_train_classes:
        before = len(test_docs)
        test_docs = [d for d in test_docs
                     if int(d[label_field]) in train_classes_set]
        n_filtered = before - len(test_docs)
        print(f"[setup] --restrict-to-train-classes ON: dropped {n_filtered} "
              f"test docs whose true class has no demo "
              f"({n_filtered}/{before} = {n_filtered/max(before,1):.1%})")
    else:
        print(f"[setup] --no-restrict-to-train-classes: keeping all "
              f"{len(test_docs)} test docs (some will be structurally "
              f"unanswerable for TL)")

    rng = random.Random(args.seed)
    rng.shuffle(test_docs)
    n_queries = min(args.n_queries, len(test_docs))
    test_docs = test_docs[:n_queries]
    print(f"[setup] using {n_queries} test docs (of {total_docs_pre_filter} "
          f"raw test set, shuffled with seed={args.seed})")

    # Abstract labels (deterministic from seed)
    if args.label_type == "single_token":
        # Empirical discovery: need a sample of how the prompt ends to pick labels.
        # Render one prompt to grab the tail.
        sample_doc = test_docs[0]
        sample_prompt = task_obj.doc_to_text(sample_doc)
        if args.reuse_labels:
            # Adopt a frozen mapping instead of re-deriving one. The discovery
            # below reads a SAMPLE PROMPT, and that prompt differs per demo
            # seed, so each seed would otherwise get its own label set and the
            # candidate tokens would drift between seeds -- a difference that
            # shows up nowhere until the three seeds are compared.
            _prev = None
            with open(args.reuse_labels, encoding="utf-8") as _f:
                for _line in _f:
                    _obj = json.loads(_line)
                    if _obj.get("header"):
                        _prev = _obj
                        break
            if _prev is None or not _prev.get("abstract_labels"):
                raise SystemExit(
                    f"--reuse-labels {args.reuse_labels}: no header with "
                    "abstract_labels")
            from tools.label_space import provenance_mismatch
            _bad = []
            if _prev.get("model") != args.model:
                _bad.append(f"model {_prev.get('model')!r} vs {args.model!r}")
            # task and n_classes stay hard: a different label vocabulary
            # or a different NUMBER of surfaces is a different object. K is
            # the one that can be crossed on purpose -- see
            # --allow-different-K for why crossing it is required rather than
            # merely allowed.
            _keys = [("task", args.task), ("n_classes", n_classes)]
            if not args.allow_different_K:
                _keys.append(("K", args.K))
            for _k, _v in _keys:
                if _prev.get(_k) != _v:
                    _bad.append(f"{_k} {_prev.get(_k)!r} vs {_v!r}"
                                + (". Pass --allow-different-K if this is "
                                   "deliberate: the surfaces do not depend on "
                                   "the demo count, and reusing them is what "
                                   "keeps the candidate token set -- and so "
                                   "the NLL's denominator -- fixed across K"
                                   if _k == "K" else ""))
            if _prev.get("tokenizer_provenance"):
                _bad += [b for b in provenance_mismatch(
                    _prev["tokenizer_provenance"], _prov)
                    if not b.startswith("[advisory]")]
            else:
                _bad.append("the source header has no tokenizer_provenance; "
                            "it predates that field and cannot be verified")
            if _bad:
                raise SystemExit(
                    "--reuse-labels source does not match this run: "
                    + "; ".join(_bad)
                    + ". Surfaces may only be reused within one model and one "
                      "tokenizer; the ids are recomputed and checked below.")
            abstract_labels = list(_prev["abstract_labels"])
            print(f"[setup] --reuse-labels: adopted {len(abstract_labels)} "
                  f"frozen surfaces from {args.reuse_labels}; token ids are "
                  "recomputed by THIS tokenizer and checked against them")
        else:
            abstract_labels = discover_single_token_labels(
                tok, sample_prompt, n_classes,
                # Blacklist gold labels so uuid prompts don't collide with gold
                # (e.g. synthetic_linear's gold A-F vs. discovered A-F).
                exclude_surfaces=set(label_names),
            )
        print(f"[setup] single_token labels (first 10): {abstract_labels[:10]}")
        print(f"[setup] single_token labels (last 5):   {abstract_labels[-5:]}")
    else:
        abstract_labels = generate_abstract_labels(n_classes, args.label_type, args.seed)
        print(f"[setup] {args.label_type} labels (first 5): {abstract_labels[:5]}")

    # Render one sample to discover in-context label token ids
    sample_doc = test_docs[0]
    gold_sample = task_obj.doc_to_text(sample_doc)
    label_token_ids_gold = compute_label_token_ids(tok, gold_sample, label_names)
    with patched_abstract_labels(task_obj, args.task, abstract_labels):
        uuid_sample = task_obj.doc_to_text(sample_doc)
    label_token_ids_uuid = compute_label_token_ids(tok, uuid_sample, abstract_labels)

    print(f"[setup] gold label-token ids (first 5): {label_token_ids_gold[:5]}")
    print(f"[setup] uuid label-token ids (first 5): {label_token_ids_uuid[:5]}")
    print(f"[setup] sample prompt ends with: ...{gold_sample[-60:]!r}")

    # Fail-fast self-check: the tokens the model ACTUALLY sees after "Type:" in
    # the rendered uuid demos MUST equal label_token_ids_uuid for the matching
    # class. A mismatch (e.g. label_token_ids holding pool subword fragments
    # while demos render single chars) silently breaks every argmax-over-labels
    # accuracy measurement -> the model scores ~0 even when it ICLs perfectly.
    # See tools/check_label_token_alignment.py for the diagnostic that surfaced
    # this on a stale trec_fine_per_class file.
    _verify_label_token_ids_match_inference_context(
        tok, uuid_sample, abstract_labels, label_token_ids_uuid)

    # Sanity: label_token_ids should be all distinct (else projection collapses)
    if len(set(label_token_ids_gold)) < n_classes:
        dup = [(i, t) for i, t in enumerate(label_token_ids_gold)
               if label_token_ids_gold.count(t) > 1]
        print(f"[warn] gold label token ids contain duplicates: {dup[:10]}")
        print(f"        This means classes share first-token; projection will conflate them.")
    if len(set(label_token_ids_uuid)) < n_classes:
        dup = [(i, t) for i, t in enumerate(label_token_ids_uuid)
               if label_token_ids_uuid.count(t) > 1]
        print(f"[warn] uuid label token ids contain duplicates: {dup[:10]}")

    # ---- Output files ----
    # The filename carries task, K and seed but NOT the model, so two models'
    # files collide in one directory and the second silently replaces the
    # first. Separate directories per model are the convention
    # (data/method_a/llama31/, data/method_a/llama2/); this refuses to write
    # into a directory that already holds another model's calibration, so the
    # convention does not have to be remembered.
    from tools.label_space import output_dir_conflict as _dir_conflict
    _present = {}
    # Every calibration file, not just the uuid one: gold, random and
    # random_uuid share the base name and would be overwritten too.
    for _existing in sorted(output_dir.glob("calibration_*.jsonl")):
        try:
            with open(_existing, encoding="utf-8") as _f:
                _h = json.loads(_f.readline())
        except Exception:
            _h = None
        _present[_existing.name] = _h if (_h or {}).get("header") else None
    _conflict = _dir_conflict(_present, args.model)
    if _conflict:
        raise SystemExit(
            f"{output_dir} already holds calibration that is not this run's: "
            + "; ".join(_conflict)
            + f". This run is for {args.model!r} and the filenames do not carry "
              "the model, so writing here would overwrite. Use a per-model "
              "directory, e.g. --output data/method_a/<model-tag>/, or move the "
              "existing files aside deliberately.")
    base = f"calibration_{args.task}_K{args.K}_seed{args.seed}"
    gold_path = output_dir / f"{base}_gold.jsonl"
    random_path = output_dir / f"{base}_random.jsonl"
    uuid_path = output_dir / f"{base}_uuid.jsonl"
    random_uuid_path = output_dir / f"{base}_random_uuid.jsonl"

    common = {
        "header": True,
        "task": args.task,
        "K": args.K,
        "seed": args.seed,
        "n_classes": n_classes,
        "n_queries": n_queries,
        # WHICH GUARD WAS CROSSED, in the artifact rather than in a shell
        # history. A file whose surfaces came from another K reads exactly
        # like one that discovered its own unless it says so.
        "reuse_labels_source": (str(args.reuse_labels)
                                if args.reuse_labels else None),
        "reuse_labels_crossed_K": bool(args.reuse_labels
                                       and args.allow_different_K),
        "label_names_original": list(label_names),
        "train_class_indices": train_classes,             # which class ids have >=1 train demo
        "n_train_classes": n_train_classes,                # |train_class_indices|
        "restrict_to_train_classes": bool(args.restrict_to_train_classes),
        "restrict_to_test_classes": bool(args.restrict_to_test_classes),
        "exclude_validation": args.exclude_validation,
        # WHICH TOKENIZER. label_token_ids are the ids of the abstract
        # labels UNDER THIS TOKENIZER, and discover_single_token_labels
        # even picks the label strings by what tokenizes to one token here.
        # A file built with one model and consumed by another yields valid
        # but wrong ids, and until this field existed nothing recorded it.
        "model": args.model,
        # Full provenance, not just the model string: two checkouts of "the
        # same" model can tokenize differently (Transformers version, revision,
        # a patched special-token map), and label_token_ids are only meaningful
        # relative to the tokenizer that produced them.
        "tokenizer_provenance": _prov,
        "query_manifest": args.exclude_validation,
        "query_manifest_sha256": _man_sha,
        "eligible_class_indices": eligible,
        "n_eligible_classes": len(eligible),
    }
    gold_hdr = {**common, "label_scheme": "gold",
                "label_token_ids": label_token_ids_gold}
    rand_hdr = {**common, "label_scheme": "random_pan",
                "M_random": args.M_random,
                "label_token_ids": label_token_ids_gold}   # target stays gold
    uuid_hdr = {**common, "label_scheme": "uuid",
                "label_type": args.label_type,
                "abstract_labels": abstract_labels,
                "label_token_ids": label_token_ids_uuid}
    rand_uuid_hdr = {**common, "label_scheme": "random_uuid",
                     "M_random": args.M_random,
                     "label_type": args.label_type,
                     "abstract_labels": abstract_labels,
                     "label_token_ids": label_token_ids_uuid}   # target = uuid of true class

    # ---- Render ----
    print(f"\n[run] rendering {n_queries} queries x "
          f"(gold + {args.M_random} random + 1 uuid + {args.M_random} random_uuid)...")
    with gold_path.open("w", encoding="utf-8") as fg, \
            random_path.open("w", encoding="utf-8") as fr, \
            uuid_path.open("w", encoding="utf-8") as fu, \
            random_uuid_path.open("w", encoding="utf-8") as fru:
        fg.write(json.dumps(gold_hdr) + "\n")
        fr.write(json.dumps(rand_hdr) + "\n")
        fu.write(json.dumps(uuid_hdr) + "\n")
        fru.write(json.dumps(rand_uuid_hdr) + "\n")

        for doc_idx, doc in enumerate(test_docs):
            true_class_idx = int(doc[label_field])

            # GOLD
            gold_prompt = task_obj.doc_to_text(doc)
            fg.write(json.dumps({
                "prompt": gold_prompt,
                "true_label_token_id": label_token_ids_gold[true_class_idx],
                "doc_idx": doc_idx,
                "true_class_idx": true_class_idx,
                "task": args.task,
                "K": args.K,
                "label_scheme": "gold",
            }) + "\n")

            # RANDOM x M (Pan-Random on real label space)
            for s in range(args.M_random):
                seed_s = args.seed * 1000 + s
                with patched_random_labels(task_obj, args.task, seed=seed_s):
                    rand_prompt = task_obj.doc_to_text(doc)
                fr.write(json.dumps({
                    "prompt": rand_prompt,
                    "true_label_token_id": label_token_ids_gold[true_class_idx],
                    "doc_idx": doc_idx,
                    "true_class_idx": true_class_idx,
                    "task": args.task,
                    "K": args.K,
                    "label_scheme": "random_pan",
                    "random_seed_s": seed_s,
                }) + "\n")

            # UUID (consistent class -> UUID mapping)
            with patched_abstract_labels(task_obj, args.task, abstract_labels):
                uuid_prompt = task_obj.doc_to_text(doc)
            fu.write(json.dumps({
                "prompt": uuid_prompt,
                "true_label_token_id": label_token_ids_uuid[true_class_idx],
                "doc_idx": doc_idx,
                "true_class_idx": true_class_idx,
                "task": args.task,
                "K": args.K,
                "label_scheme": "uuid",
            }) + "\n")

            # RANDOM_UUID x M (UUID labels with per-demo random assignment)
            # Used as the prior-clean C_rand contrast for TL-score discovery.
            for s in range(args.M_random):
                seed_s = args.seed * 2000 + s   # offset from random_pan seeds
                with patched_random_abstract_labels(
                    task_obj, args.task, abstract_labels, seed=seed_s
                ):
                    rand_uuid_prompt = task_obj.doc_to_text(doc)
                fru.write(json.dumps({
                    "prompt": rand_uuid_prompt,
                    "true_label_token_id": label_token_ids_uuid[true_class_idx],
                    "doc_idx": doc_idx,
                    "true_class_idx": true_class_idx,
                    "task": args.task,
                    "K": args.K,
                    "label_scheme": "random_uuid",
                    "random_seed_s": seed_s,
                }) + "\n")

            if (doc_idx + 1) % 10 == 0 or doc_idx == n_queries - 1:
                print(f"  [{doc_idx + 1}/{n_queries}] rendered")

    print(f"\n[output] {gold_path}        ({n_queries} prompts)")
    print(f"[output] {random_path}      ({n_queries * args.M_random} prompts)")
    print(f"[output] {uuid_path}        ({n_queries} prompts)")
    print(f"[output] {random_uuid_path} ({n_queries * args.M_random} prompts)")

    # ---- Sanity print: token-count distribution ----
    print()
    for scheme, path in [
        ("gold", gold_path),
        ("uuid", uuid_path),
        ("random", random_path),
        ("random_uuid", random_uuid_path),
    ]:
        ns = []
        with path.open() as f:
            next(f)  # header
            for line in f:
                obj = json.loads(line)
                ns.append(len(tok(obj["prompt"], add_special_tokens=True).input_ids))
        if ns:
            print(f"[token counts: {scheme}]  "
                  f"n={len(ns)}  min={min(ns)}  median={int(statistics.median(ns))}  "
                  f"max={max(ns)}  mean={int(statistics.mean(ns))}")

    # ---- Sanity print: one sample of each ----
    print("\n[sample uuid prompt, first 200 + last 100 chars]")
    with uuid_path.open() as f:
        next(f)
        first = json.loads(next(f))
    p = first["prompt"]
    print(f"  ...{p[:200]!r}")
    print(f"     [{len(p) - 300} chars omitted]" if len(p) > 300 else "")
    print(f"  ...{p[-100:]!r}")
    print(f"  true_label_token_id = {first['true_label_token_id']} "
          f"(class {first['true_class_idx']})")


if __name__ == "__main__":
    main()
